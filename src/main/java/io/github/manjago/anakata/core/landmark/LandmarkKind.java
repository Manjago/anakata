package io.github.manjago.anakata.core.landmark;

/**
 * Вид примечательности — род ориентира, внутри которого различаются варианты.
 *
 * <p><b>Порядок констант вместе с их числом — часть контракта сида.</b> Вид
 * клетки — остаток от деления хеша на число видов, поэтому добавление седьмой
 * константы перераскладывает виды по клеткам даже в конце списка, а перестановка
 * существующих меняет их все. Менять состав можно только с осознанием, что
 * ориентиры по всем опубликованным сидам станут другими.
 *
 * <p>Русские названия видов живут в пакете описаний: ядро не знает, как вид
 * называется игроку.
 */
public enum LandmarkKind {
    OBJECT,
    WALL_PATTERN,
    FLOOR_TEXTURE,
    LIGHT,
    SOUND,
    SMELL;

    /**
     * Число вариантов у каждого вида — тоже часть контракта сида: вариант клетки
     * берётся остатком от деления на это число, поэтому его рост иначе разложит
     * варианты по всем уже опубликованным сидам.
     */
    public static final int VARIANTS = 8;
}
