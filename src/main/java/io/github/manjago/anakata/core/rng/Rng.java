package io.github.manjago.anakata.core.rng;

/**
 * Источник псевдослучайных значений, используемый ядром.
 *
 * <p>Генератор ручной, детерминированный: экземпляр, созданный из одного и того же
 * начального состояния, порождает одну и ту же последовательность. Умеет отдавать
 * неизменяемый снимок своего состояния для сохранения и восстанавливаться из него.
 */
public interface Rng {

    /** Следующее 64-битное псевдослучайное значение. */
    long nextLong();

    /** Следующее псевдослучайное значение из диапазона {@code [0, bound)}. */
    long nextLong(long bound);

    /** Следующее псевдослучайное значение из диапазона {@code [0, bound)}, {@code bound > 0}. */
    int nextInt(int bound);

    /** Следующее псевдослучайное логическое значение. */
    boolean nextBoolean();

    /** Неизменяемый снимок текущего состояния для сохранения и восстановления. */
    RngState state();
}
