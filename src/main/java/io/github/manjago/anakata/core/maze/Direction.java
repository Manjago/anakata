package io.github.manjago.anakata.core.maze;

/**
 * Направление хода вдоль одной из осей решётки.
 *
 * <p>У направления есть ось и знак: {@code sign > 0} — в сторону роста координаты
 * по этой оси. Противоположные направления отличаются младшим битом {@code bit()},
 * поэтому обратное направление — это {@code bit ^ 1}.
 *
 * <p>Четвёртая ось названа по аналогии с третьей: ана — «вверх» для неё, то есть
 * рост координаты, как {@link #UP} для третьей оси.
 *
 * <p><b>Порядок констант вместе с их осью и знаком — часть контракта сида.</b>
 * Генератор обходит {@code values()} и выбирает соседа по позиции в этом порядке,
 * поэтому и перестановка констант, и смена оси или знака у любой из них молча
 * меняют лабиринты по всем опубликованным сидам. Раскладка битов {@code bit()}
 * контрактом <em>не</em> является: маски нигде не сериализуются, лабиринт
 * перегенерируется из сида, поэтому биты можно менять свободно. Словарные названия
 * направлений живут в пакете описаний, здесь только оси и знаки.
 */
public enum Direction {
    NORTH(0, 1),
    SOUTH(0, -1),
    EAST(1, 1),
    WEST(1, -1),
    UP(2, 1),
    DOWN(2, -1),
    ANA(3, 1),
    KATA(3, -1);

    /** Таблица «номер бита → направление» для обращения младшего бита. */
    private static final Direction[] BY_BIT = new Direction[8];

    static {
        for (Direction direction : values()) {
            BY_BIT[direction.bit()] = direction;
        }
    }

    private final int axis;
    private final int sign;

    Direction(int axis, int sign) {
        this.axis = axis;
        this.sign = sign;
    }

    /** Индекс оси, вдоль которой идёт ход. */
    public int axis() {
        return axis;
    }

    /** Знак смещения координаты: {@code +1} — рост, {@code -1} — убывание. */
    public int sign() {
        return sign;
    }

    /** Номер бита направления в маске выходов клетки. */
    int bit() {
        return 2 * axis + (sign > 0 ? 1 : 0);
    }

    /** Противоположное направление — вдоль той же оси, с другим знаком. */
    public Direction opposite() {
        return BY_BIT[bit() ^ 1];
    }
}
