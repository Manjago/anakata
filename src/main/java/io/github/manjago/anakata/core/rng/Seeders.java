package io.github.manjago.anakata.core.rng;

/**
 * Фабрика сидераторов — детерминированных ответвлений потока от базового сида.
 *
 * <p>От одного корневого генератора через {@link #branch(Rng, String)} можно получить
 * независимые «параллельные» потоки для разных задач уровня: лабиринт, расстановка
 * букв, ориентиры. Один и тот же корень и имя всегда дают один и тот же поток, поэтому
 * в снапшоте достаточно хранить базовый сид уровня — все ветки выводятся заново.
 *
 * <p>Ответвление не продвигает корневой генератор: берётся лишь снимок его текущего
 * состояния, на основе которого выводится сид ветки. Смена алгоритма RNG — смена
 * формата выводов веток (как и формата снапшота), поэтому реализация привязана к
 * {@link SplitMix64}.
 */
public final class Seeders {

    private Seeders() {
        // Утилитарный класс без экземпляров.
    }

    /**
     * Возвращает новый генератор — ответвление {@code root} с именем {@code name}.
     *
     * <p>Сид ветки — свёртка текущего состояния корня и хеша имени: {@code mix(s ^ hash)}.
     * Разные имена у одного корня дают разные, не пересекающиеся потоки.
     *
     * @param root  корневой генератор, чьё состояние не изменяется
     * @param name  имя потока, например {@code "maze"} или {@code "letters"}
     * @return новый генератор-сидератор
     */
    public static Rng branch(Rng root, String name) {
        long rootState = ((SplitMix64State) root.state()).s();
        return new SplitMix64(SplitMix64.mix(rootState ^ hashName(name)));
    }

    /**
     * 64-битная свёртка строки без внешних хешей: каждая кодовая точка смешивается
     * с накопленной суммой через разболтку SplitMix64 {@link SplitMix64#mix}.
     */
    private static long hashName(String name) {
        long h = 0x9E3779B97F4A7C15L;
        for (int i = 0; i < name.length(); i++) {
            h = SplitMix64.mix(h ^ name.charAt(i));
        }
        return h;
    }
}
