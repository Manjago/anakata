package io.github.manjago.anakata.core.game;

/**
 * Исход команды — то, чем ядро ответило на {@link Command}.
 *
 * <p>Тип назван по команде, а не по ходу: {@link Reply} отвечает на любую
 * команду, и когда появится «назвать слово», его исходы прибавятся сюда же.
 * Значения пока описывают ход.
 */
public enum Outcome {

    /** Игрок перешёл в соседнюю клетку. */
    MOVED,

    /**
     * Прохода нет: стена, край решётки или направление, которого нет в
     * размерности уровня. Такой ход не двигает игрока и не считается ходом:
     * иначе cooldown из пункта 6 сбивался бы долбёжкой в стену.
     */
    BLOCKED
}
